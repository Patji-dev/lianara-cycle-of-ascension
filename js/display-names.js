function initializeCultivationTheme() {
    const cachedText = new WeakMap();
    const cachedAttributes = new WeakMap();
    const excluded = "script,style,textarea,input,pre,code,[data-upstream-attribution]";
    function translateNode(node) {
        if (node.nodeType === Node.TEXT_NODE) {
            if (!node.parentElement || node.parentElement.closest(excluded)) return;
            const source = node.nodeValue;
            if (cachedText.get(node) === source) return;
            const translated = cultivationText(source);
            cachedText.set(node, translated);
            if (translated !== source) node.nodeValue = translated;
        } else if (node.nodeType === Node.ELEMENT_NODE && !node.matches(excluded)) {
            for (const attribute of ["title", "aria-label", "alt"]) {
                const source = node.getAttribute(attribute);
                if (source === null) continue;
                const previous = cachedAttributes.get(node) || {};
                if (previous[attribute] === source) continue;
                const translated = cultivationText(source);
                previous[attribute] = translated; cachedAttributes.set(node, previous);
                if (translated !== source) node.setAttribute(attribute, translated);
            }
            for (const child of node.childNodes) translateNode(child);
        }
    }
    translateNode(document.body);
    const observer = new MutationObserver(records => {
        for (const record of records) {
            if (record.type === "childList") for (const node of record.addedNodes) translateNode(node);
            else translateNode(record.target);
        }
    });
    observer.observe(document.body, {subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:["title","aria-label","alt"]});
}
