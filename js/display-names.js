let cultivationTextMatcher;
let cultivationTextLookup;
let cultivationProtectedTerms;
function cultivationText(value) {
    const text = String(value ?? "");
    if (!cultivationTextMatcher) {
        const entries = [...Object.entries(CULTIVATION_TERMS), ...Object.entries(CULTIVATION_DISPLAY_NAMES)];
        cultivationTextLookup = new Map(entries.map(([key, value]) => [key.toLowerCase(), value]));
        cultivationProtectedTerms = new Set(entries.map(([,value]) => value.toLowerCase()));
        const phrases = [...new Set([...entries.map(([key])=>key), ...entries.map(([,value])=>value)])];
        const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        cultivationTextMatcher = new RegExp("(?<![\\p{L}\\p{N}_])(?:" + phrases.sort((a,b)=>b.length-a.length).map(escape).join("|") + ")(?![\\p{L}\\p{N}_])", "giu");
    }
    return text.replace(cultivationTextMatcher, match => cultivationProtectedTerms.has(match.toLowerCase())
        ? match : cultivationTextLookup.get(match.toLowerCase()) || match);
}

